package Language_fundamentals.Home_work1.assign2;

public class calculator {
    public static void main(String[] args){
        int num1 = 65;
        int num2 = 47;
        int add = num1 + num2;
        int sub = num1 - num2;
        int mul = num1*num2;
        int div = num1/num2;
        int mod = num1%num2;
        System.out.println("-----------------------Basic calculator ops--------------------------");
        System.out.println("the addition operation is:" + add);
        System.out.println("The subtraction operation is:" + sub);
        System.out.println("the multiplication is " + mul);
        System.out.println("the division is" + div);
        System.out.println("the modulo operation is " + mod);
    }
}
